#!/usr/bin/env node
// Generates the smaller WebP derivatives the site serves to phones.
//
// Two sources of avoidable weight were measured on the built site at 390px:
//   - catalogue cards paint at roughly 100-160px CSS but were served the full
//     product assets, 3.5MB across the index;
//   - the brand logo is a 900x741 PNG of 263KB, loaded in the header and footer
//     of every single page, to be painted at about 50-80px.
// Both are fixed by offering a small WebP first through srcset. The originals
// stay in place and remain what the product and brand pages reference.
//
// The widths are chosen against the measured paint box, not a guess: the card
// stage resolves to 126 CSS px on a 390px phone and at most 168px on desktop.
// That means 256w for a 2x phone, 384w for a 3x phone, 512w for a 3x desktop.
// Getting this wrong is expensive in both directions — a ladder that stopped at
// 320w made 2x and 3x phones fall back to the full asset, and a 640w rung made
// them download four times the pixels the box can paint.
//
// Owner-supplied originals are never modified: derivatives are written to
// separate files, and every source image's SHA-256 is checked before and after
// the run. The ISO Gelcoat poster is displayed from its original; the ISO
// Polyester and UV Sheet Grade Yellow posters are displayed from corrected
// copies (see products.js), and their originals stay in public/ unlinked.
//
// Large posters (300KB and over) also get display derivatives for the product
// page gallery: 480w, 720w, 960w and a full-width WebP for 3x phones.
//
// Run after adding or replacing an image:  npm run build:images

import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import sharp from 'sharp';
import { products } from '../src/data/products.js';

const SRC = 'public/images/products';
const OUT = path.join(SRC, 'cards');
const CARD_WIDTHS = [256, 384, 512];
const DISPLAY_OUT = path.join(SRC, 'display');
const DISPLAY_WIDTHS = [480, 720, 960];
const DISPLAY_MIN_BYTES = 300 * 1024;

const sha = (file) => crypto.createHash('sha256').update(fs.readFileSync(file)).digest('hex');
const sourceHashes = new Map(
  fs
    .readdirSync(SRC)
    .filter((f) => /\.(jpe?g|png|webp)$/i.test(f))
    .map((f) => [f, sha(path.join(SRC, f))]),
);

fs.mkdirSync(OUT, { recursive: true });

const made = [];
let before = 0;
let after = 0;

for (const product of products) {
  const image = product.images?.[0];
  if (!image) continue;
  const from = path.join(SRC, image.src);
  if (!fs.existsSync(from)) continue;

  for (const width of CARD_WIDTHS) {
    const to = path.join(OUT, image.src.replace(/\.(jpe?g|png|webp)$/i, `-${width}.webp`));
    await sharp(from).resize({ width, withoutEnlargement: true }).webp({ quality: 70 }).toFile(to);
    after += fs.statSync(to).size;
  }
  before += fs.statSync(from).size;
  made.push(image.src);
}

fs.mkdirSync(DISPLAY_OUT, { recursive: true });
const displayed = [];
for (const product of products) {
  for (const image of product.images ?? []) {
    const from = path.join(SRC, image.src);
    if (displayed.includes(image.src) || !fs.existsSync(from)) continue;
    if (fs.statSync(from).size < DISPLAY_MIN_BYTES) continue;
    for (const width of DISPLAY_WIDTHS) {
      const to = path.join(DISPLAY_OUT, image.src.replace(/\.(jpe?g|png|webp)$/i, `-${width}.webp`));
      await sharp(from).resize({ width, withoutEnlargement: true }).webp({ quality: 80 }).toFile(to);
    }
    // Full-width WebP: a 3x phone paints the gallery at ~1,035 device px, above
    // the 960w rung, and would otherwise fall back to the full JPEG.
    const full = path.join(DISPLAY_OUT, image.src.replace(/\.(jpe?g|png|webp)$/i, '-full.webp'));
    await sharp(from).webp({ quality: 80 }).toFile(full);
    displayed.push(image.src);
  }
}

fs.writeFileSync(
  'src/data/display-derivatives.js',
  '// Generated by scripts/build-image-derivatives.mjs — do not edit by hand.\n' +
    '// A product image listed here has 480w, 720w, 960w and full-width WebP copies in\n' +
    '// /images/products/display/ for the product page gallery.\n' +
    'export const displayDerivatives = new Set([\n' +
    displayed.map((s) => `  '${s}',`).join('\n') +
    '\n]);\n',
);

fs.writeFileSync(
  'src/data/card-derivatives.js',
  '// Generated by scripts/build-image-derivatives.mjs — do not edit by hand.\n' +
    '// A product listed here has 256w, 384w and 512w WebP cards in\n' +
    '// /images/products/cards/. The source files themselves are never modified.\n' +
    'export const cardDerivatives = new Set([\n' +
    made.map((s) => `  '${s}',`).join('\n') +
    '\n]);\n',
);

// Brand chrome. The logo is on every page, so its weight is paid on every page.
// Transparency is preserved, and the original stays in place for the JSON-LD
// logo and video thumbnail URLs, which are consumed by machines rather than
// painted in the layout.
const BRAND = [
  { from: 'public/brand/samrat-frp-traders-logo.png', width: 320 },
  // The brand film's still frame is eager-loaded on the homepage and is now
  // what a phone sees in place of the 12MB film, so its own weight matters.
  { from: 'public/videos/brand-showcase-still.jpeg', width: 900 },
];
let brandBefore = 0;
let brandAfter = 0;
for (const asset of BRAND) {
  if (!fs.existsSync(asset.from)) continue;
  const to = asset.from.replace(/\.(png|jpe?g)$/i, `-${asset.width}.webp`);
  await sharp(asset.from)
    .resize({ width: asset.width, withoutEnlargement: true })
    .webp({ quality: 82 })
    .toFile(to);
  brandBefore += fs.statSync(asset.from).size;
  brandAfter += fs.statSync(to).size;
}

console.log(`card derivatives: ${made.length} products x ${CARD_WIDTHS.join('w, ')}w`);
console.log(`  ${Math.round(before / 1024)}KB of originals -> ${Math.round(after / 1024)}KB of cards`);
console.log(`display derivatives: ${displayed.length} images x ${DISPLAY_WIDTHS.join('w, ')}w + full width`);
for (const [file, hash] of sourceHashes) {
  if (sha(path.join(SRC, file)) !== hash) throw new Error(`source image changed during the run: ${file}`);
}
console.log(`  ${sourceHashes.size} source images unchanged (SHA-256 checked)`);
console.log(`brand derivatives: ${Math.round(brandBefore / 1024)}KB -> ${Math.round(brandAfter / 1024)}KB`);
